def _hit(pat, text):
    """词表里允许写正则（如 "第一(、|，|：)"），用来区分序号与序数。"""
    try:
        return re.search(pat, text) is not None
    except re.error:
        return pat in text


# 2026-11-27 18:1x 修：引用/举例里的词不算「我在这么说」。
# 起因：今日事实里「12.3 万字里 综上/值得注意的是 只出现 1 次」是**在数词**，却被判成硬拒；
# 假阳一多，红灯就被学会忽略（比漏报更坏）。
QUOTED = re.compile(r'`[^`]*`|"[^"]{1,80}"|“[^”]{1,80}”|「[^」]{1,80}」|『[^』]{1,80}』|\'[^\']{1,40}\'')


def strip_quoted(text):
    """把引用/代码/书名号里的内容挖掉，只留我自己说的话。返回 (裸文本, 被挖掉的片段数)。"""
    n = 0
    def _rep(m):
        nonlocal n
        n += 1
        return ' '
    return QUOTED.sub(_rep, text), n


def scan(text, exempt_quotes=True):
    """返回 (硬拒命中, 警示命中)。默认豁免引号内内容（引用别人/举例不算我在说）。"""
    body = strip_quoted(text)[0] if exempt_quotes else text
    hard = [w for w in HARD if _hit(w, body)]
    warn = [w for w in WARN if _hit(w, body)]
    return hard, warn


def count_warn(text):
    """警示词不搞零容忍——人也会说"总的来说"。一段里超过 1 处才算犯了。"""
    hard, warn = scan(text)
    return len(hard), len(warn)


def report(text):
    hard, warn = scan(text)
    if hard:
        return '✗ 不许过（A1 语气词 %d 处）：%s' % (len(hard), '、'.join(hard))
    if len(warn) >= 2:
        return '△ 警示（%d 处）：%s —— 一句里说这么多连接词，是在打官腔' % (len(warn), '、'.join(warn))
    if warn:
        return '· 有一处（%s）—— 人也会这么说，自己看着办' % '、'.join(warn)
    return '✓ 干净'
